def refine_file(filepath):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    # Iterate over CURATED_DICT
    count = 0
    for hanzi, tr in CURATED_DICT.items():
        # Match block with hanzi: "..."
        pattern = rf'(\{{\s*hanzi:\s*"{re.escape(hanzi)}",\s*pinyin:\s*"[^"]*",\s*indonesian:\s*)"[^"]*"(,\s*malay:\s*)"[^"]*"(,\s*english:\s*)"[^"]*"'
        def repl(m):
            nonlocal count
            count += 1
            return f'{m.group(1)}"{tr["id"]}"{m.group(2)}"{tr["ms"]}"{m.group(3)}"{tr["en"]}"'
        content = re.sub(pattern, repl, content)

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"Refined {count} entries in {filepath}")

